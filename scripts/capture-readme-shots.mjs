/**
 * Captures the README's appearance pair from the RUNNING GUI — one real screenshot
 * of the running app per appearance, with a real conversation on screen, flattened
 * into one image.
 *
 * What is real and what is not, because this image has to be honest:
 *
 *   REAL      the application, its layout, the sidebar chrome, the header, the
 *             composer, the message/tool/deliverable blocks and their geometry —
 *             the capture is a session page of this machine's own GUI, rendered by
 *             the skin the profile has installed.
 *   FAKE      every piece of text inside those blocks, plus the workspace names and
 *             session titles. The conversation structure is the real one; the words
 *             are generated by this script from small phrase libraries, so no
 *             conversation of the user's ends up in the repository.
 *
 * Three things this script refuses to do:
 *
 *   1. It does not write to the user's settings to get the light column. The
 *      appearance is a durable Host preference (`ui-theme`), and flipping it through
 *      the settings UI would change the app the user is looking at. The light pass
 *      instead rewrites two responses inside its own throwaway browser: the
 *      document's boot rows and `/api/settings/describe`, which is where the theme
 *      client reads the preference from. Nothing on disk changes.
 *   2. It does not ship the user's data. Sidebar rows are replaced with placeholders
 *      and every text leaf in the transcript, docks and header is replaced before the
 *      shutter; both passes re-check the rendered text and FAIL rather than write a
 *      screenshot in which any original string survives.
 *   3. It does not pretend the fake text is real. The README says so, and the masks
 *      are visible in the failure path only — never in the image.
 *
 * Run: make sure `dsh web` is up (the URL is read from ~/.dsh-web.out.log, or set
 *      $env:DSH_URL), then:
 *        node scripts/capture-readme-shots.mjs
 * Output: docs/images/skin-themes.png  (+ tests/out/skin-{dark,light}.png, gitignored)
 */
