/** The URL `dsh web` printed; the launcher's log is the source of truth here too. */
function dshUrl() {
  if (process.env.DSH_URL) return process.env.DSH_URL
  const log = join(homedir(), '.dsh-web.out.log')
  const text = readFileSync(log, 'utf8')
  const found = [...text.matchAll(/http:\/\/\S*token=\S*/g)].map((m) => m[0])
  if (found.length === 0) throw new Error(`no dsh web URL in ${log} (start it, or set $env:DSH_URL)`)
  return found[found.length - 1]
}

